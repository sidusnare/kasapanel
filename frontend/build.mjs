// Bundles the React sources into kasapanel/static/bundle.js.  The result
// is committed, so installing the daemon needs no Node at all; you only
// need this when you change something under frontend/src.

import { build, context } from 'esbuild';
import process from 'node:process';

const options = {
  entryPoints: ['src/main.jsx'],
  bundle: true,
  format: 'iife',
  target: ['es2020'],
  minify: true,
  legalComments: 'none',
  outfile: '../kasapanel/static/bundle.js',
  define: { 'process.env.NODE_ENV': '"production"' },
  // The bundle is a shipped file, so it carries its own REUSE header.
  // Each tag sits alone on its line with nothing after the expression:
  // a trailing comment close on the same line cannot be parsed as a
  // licence expression.
  banner: {
    js: [
      '/*',
      ' * SPDX-FileCopyrightText: 2026 Kasa Panel contributors',
      ' *',
      ' * SPDX-License-Identifier: GPL-3.0-or-later AND MIT',
      ' *',
      ' * SPDX-FileContributor: Claude Opus 5 (AI-generated)',
      ' * AI usage declaration: docs/ai-bom.spdx.json',
      ' *',
      ' * Generated by frontend/build.mjs; edit frontend/src instead.',
      ' * Bundles React and ReactDOM (MIT, Meta Platforms).',
      ' */',
    ].join('\n'),
  },
};

if (process.argv.includes('--watch')) {
  const ctx = await context(options);
  await ctx.watch();
  console.log('watching frontend/src');
} else {
  await build(options);
  console.log('wrote kasapanel/static/bundle.js');
}
